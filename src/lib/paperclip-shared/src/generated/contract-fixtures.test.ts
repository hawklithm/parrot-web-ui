/**
 * Rust↔TS bidirectional contract gate (plan §6B.1 item 684).
 *
 * `contract-fixtures.json` is generated by the Rust test
 * `crates/services/tests/contract_fixture_test.rs` from the canonical Rust
 * tables. This suite asserts the controlled TS tables match it exactly; the
 * Rust side asserts the committed fixture matches the Rust tables. Any drift
 * in either language breaks one of the two gates.
 */
const fixturePath = new URL("./contract-fixtures.json", import.meta.url);
const fixture = JSON.parse(readFileSync(fixturePath, "utf8")) as {
  plugin: Record<string, readonly string[]>;
  toolAccess: Record<string, readonly string[]>;
};

